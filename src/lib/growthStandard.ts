/** 월령(소수). 한 달 = 30.4375일. */
export function ageInMonths(birth: string, date: string): number {
  return (Date.parse(date) - Date.parse(birth)) / 86_400_000 / 30.4375
}

/** 표 범위 안이면 앞뒤 행을 직선 보간, 밖이면 null. */
export function standardAt(sex: BabySex, metric: Metric, months: number): { p3: number; p50: number; p97: number } | null {
  const rows = GROWTH_STANDARD[sex][metric]
  if (rows.length === 0 || months < rows[0][0] || months > rows[rows.length - 1][0]) return null
  let i = 0
  while (i + 1 < rows.length && rows[i + 1][0] <= months) i++
  const a = rows[i]
  const b = rows[i + 1] ?? a
  const t = b[0] === a[0] ? 0 : (months - a[0]) / (b[0] - a[0])
  const lerp = (k: 1 | 2 | 3) => a[k] + (b[k] - a[k]) * t
  return { p3: lerp(1), p50: lerp(2), p97: lerp(3) }
}

/** 표에 3·50·97 만 있어 그 사이 구간으로만 말한다. */
export function bandLabel(value: number, s: { p3: number; p50: number; p97: number }): string {
  if (value < s.p3) return '3% 미만'
  if (value < s.p50) return '3~50%'
  if (value <= s.p97) return '50~97%'
  return '97% 초과'
}

/** 값이 있는 마지막 기록과 그 직전 기록의 차이. rows 는 측정일 오름차순. */
export function latestDelta<T>(rows: readonly T[], pick: (r: T) => number | null): { value: number; delta: number | null } | null {
  const vals = rows.map(pick).filter((v): v is number => v != null)
  if (vals.length === 0) return null
  const value = vals[vals.length - 1]
  return { value, delta: vals.length > 1 ? value - vals[vals.length - 2] : null }
}
